CREATE TABLE IF NOT EXISTS TB_EEP_HR_STAFF_PRJ_VER_H (
	  VER_SQ        int NOT NULL AUTO_INCREMENT
	, STAFF_SQ      int NOT NULL
	, VER_NO        int NOT NULL
	, SNAPSHOT      longtext NOT NULL COMMENT '그 버전의 수행이력 전체(JSON 배열)'
	, SUMMARY       varchar(500) NULL COMMENT '직전 버전과 달라진 점'
	, PRJ_CNT       int NOT NULL DEFAULT 0
	, REG_EMPLY_ID  varchar(50) NULL
	, REG_DT        datetime NULL
	, PRIMARY KEY (VER_SQ)
	, UNIQUE KEY UX_STAFF_PRJ_VER (STAFF_SQ, VER_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='직원 수행이력 버전';

CREATE TABLE IF NOT EXISTS TB_EEP_HR_STAFF_PRJ_LOG_H (
	  LOG_SQ        int NOT NULL AUTO_INCREMENT
	, STAFF_SQ      int NOT NULL
	, ACT_CD        varchar(10) NOT NULL COMMENT 'ADD, EDIT, DEL, IMPORT, RESTORE, VERSION'
	, PRJ_NM        varchar(300) NULL
	, DETAIL        varchar(1000) NULL
	, REG_EMPLY_ID  varchar(50) NULL
	, REG_DT        datetime NULL
	, PRIMARY KEY (LOG_SQ)
	, KEY IX_STAFF_PRJ_LOG (STAFF_SQ, LOG_SQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='직원 수행이력 건별 변경 기록';

