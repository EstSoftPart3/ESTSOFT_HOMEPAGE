-- 되돌리기: DROP TABLE TB_EEP_DEPLOY_CHG_H, TB_EEP_DEPLOY_MEMO_R;

CREATE TABLE IF NOT EXISTS TB_EEP_DEPLOY_CHG_H (
	  CHG_SQ      bigint NOT NULL AUTO_INCREMENT
	, DEPLOY_SQ   int NOT NULL COMMENT '지운 건도 이력은 남는다'
	, STAFF_SQ    int NOT NULL
	, FIELD_NM    varchar(30) NOT NULL COMMENT '칸 이름, NEW 등록, DELETE 삭제'
	, BEFORE_VAL  varchar(500) NULL
	, AFTER_VAL   varchar(500) NULL
	, REASON      varchar(200) NULL
	, REVERTED_YN char(1) NOT NULL DEFAULT 'N'
	, EMPLY_ID    varchar(50) NOT NULL
	, REG_DT      datetime NOT NULL DEFAULT CURRENT_TIMESTAMP
	, PRIMARY KEY (CHG_SQ)
	, KEY IX_DEPLOY_CHG_STAFF (STAFF_SQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='투입 수정이력';

CREATE TABLE IF NOT EXISTS TB_EEP_DEPLOY_MEMO_R (
	  MEMO_SQ  bigint NOT NULL AUTO_INCREMENT
	, STAFF_SQ int NOT NULL
	, CONTENT  varchar(1000) NOT NULL
	, EMPLY_ID varchar(50) NOT NULL
	, REG_DT   datetime NOT NULL DEFAULT CURRENT_TIMESTAMP
	, PRIMARY KEY (MEMO_SQ)
	, KEY IX_DEPLOY_MEMO_STAFF (STAFF_SQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='투입 메모 (쌓기만, 본인 것만 삭제). 급여 메모와 따로 둬 급여 권한이 없는 사람도 쓴다';
