-- 관리자 자동로그인 토큰 (2026-11-02)
-- 되돌리기: DROP TABLE TB_EEP_EMPLY_LOGIN_TKN;
-- 토큰 원문은 쿠키에만 있고 여기에는 해시만 둔다. PW_HASH 가 현재 비밀번호와 다르면 쓸 수 없어 비밀번호를 바꾸면 자동로그인이 풀린다
CREATE TABLE TB_EEP_EMPLY_LOGIN_TKN (
	TOKEN_HASH CHAR(64) NOT NULL,
	EMPLY_SQ   INT      NOT NULL,
	PW_HASH    CHAR(64) NOT NULL,
	EXPIRE_DT  DATETIME NOT NULL,
	REG_DT     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (TOKEN_HASH),
	KEY IX_EMPLY_LOGIN_TKN_EXPIRE (EXPIRE_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
