-- 휴대폰 알림(텔레그램 봇) 2026-11-20. 앱 기동 때 TelegramService.ensureSchema 가 같은 내용을 만든다(이미 있으면 그대로).
-- 봇 토큰·봇 아이디·사이트 주소·읽은 메시지 번호는 기존 TB_EEP_CAL_CONF_M 에 TELEGRAM_* 키로 들어간다(토큰은 RrnCipher 암호). 내 연동 화면에서 슈퍼관리자가 넣는다.
-- 되돌리기: DROP TABLE TB_EEP_TG_LINK_R, TB_EEP_TG_SEND_H, TB_EEP_TG_EVT_S; DELETE FROM TB_EEP_CAL_CONF_M WHERE CONF_KEY LIKE 'TELEGRAM\_%';

CREATE TABLE IF NOT EXISTS TB_EEP_TG_LINK_R (
	  EMPLY_ID     VARCHAR(50)  NOT NULL PRIMARY KEY COMMENT '관리자 아이디'
	, CHAT_ID      VARCHAR(30)  NULL COMMENT '텔레그램 대화 번호(연결 후)'
	, TG_USER_NM   VARCHAR(100) NULL COMMENT '@아이디 또는 이름(표시용)'
	, LINK_CODE    VARCHAR(40)  NULL COMMENT '1회용 연결 코드'
	, CODE_EXP_DT  DATETIME     NULL COMMENT '코드 만료(10분)'
	, STATUS_CD    VARCHAR(10)  NOT NULL DEFAULT 'WAIT' COMMENT 'WAIT 연결 전, ON 연결됨, OFF 끊김·차단'
	, KINDS        VARCHAR(100) NULL DEFAULT 'INTV_NEW,INTV_EXP,RC_INTV,MY' COMMENT 'N분 전 알림 받을 종류'
	, BEFORE_MIN   INT          NOT NULL DEFAULT 30 COMMENT '10·30·60'
	, CHANGE_KINDS VARCHAR(100) NULL COMMENT '시간 변경·취소 알림 받을 종류(기본 끔)'
	, LINK_DT      DATETIME     NULL
	, UPDT_DT      DATETIME     NULL
	, UNIQUE KEY UX_TG_CODE (LINK_CODE)
) DEFAULT CHARSET=utf8mb4 COMMENT='텔레그램 알림 연결·설정(관리자별)';

CREATE TABLE IF NOT EXISTS TB_EEP_TG_SEND_H (
	  SEND_SQ   INT          NOT NULL AUTO_INCREMENT PRIMARY KEY
	, EMPLY_ID  VARCHAR(50)  NOT NULL
	, KIND      VARCHAR(10)  NOT NULL COMMENT 'INTV_NEW·INTV_EXP·RC_INTV·MY'
	, SRC_SQ    VARCHAR(20)  NOT NULL COMMENT '면접 INTV_SQ, 모집 APPLY_SQ, 할 일 TASK_SQ'
	, EVENT_AT  VARCHAR(16)  NOT NULL COMMENT '일정 시각 yyyy-MM-dd HH:mm(취소는 옛 시각)'
	, MSG_CD    VARCHAR(10)  NOT NULL COMMENT 'BEFORE·CHANGE·CANCEL'
	, RESULT_CD VARCHAR(10)  NOT NULL COMMENT 'WAIT·OK·FAIL'
	, ERR_MSG   VARCHAR(300) NULL
	, SEND_DT   DATETIME     NOT NULL
	, UNIQUE KEY UX_TG_SEND (EMPLY_ID, KIND, SRC_SQ, EVENT_AT, MSG_CD)
	, KEY IX_TG_SEND_DT (SEND_DT)
) DEFAULT CHARSET=utf8mb4 COMMENT='텔레그램 알림 발송 기록(중복 방지, 90일 보관)';

CREATE TABLE IF NOT EXISTS TB_EEP_TG_EVT_S (
	  KIND     VARCHAR(10)  NOT NULL
	, SRC_SQ   VARCHAR(20)  NOT NULL
	, EVENT_AT VARCHAR(16)  NOT NULL
	, TITLE    VARCHAR(200) NULL
	, PRIMARY KEY (KIND, SRC_SQ)
) DEFAULT CHARSET=utf8mb4 COMMENT='텔레그램 알림 변경·취소 감지용 직전 일정 상태';
