-- 교육생 주차 자동 진행 (2026-11-16). 주차 = 시작일 주의 월요일부터 지난 주 수 + 1 + EDU_WEEK_ADJ(드래그로 옮긴 차이)
-- 되돌리기: ALTER TABLE TB_EEP_HR_TRAINEE_M DROP COLUMN EDU_WEEK_ADJ; (EDU_WEEK 는 이 작업 전 값 그대로 남아 있다)
ALTER TABLE TB_EEP_HR_TRAINEE_M ADD COLUMN EDU_WEEK_ADJ INT NOT NULL DEFAULT 0 AFTER EDU_WEEK;

-- 지금까지 드래그로 정해 둔 주차는 오늘 화면 그대로 보이게 차이로 바꿔 둔다. 이후로는 매주 월요일에 자동으로 넘어간다
UPDATE TB_EEP_HR_TRAINEE_M
SET EDU_WEEK_ADJ = IF(EDU_WEEK = 'OVER', 4, CAST(EDU_WEEK AS SIGNED))
	- (FLOOR(DATEDIFF(SUBDATE(DATE(CONVERT_TZ(UTC_TIMESTAMP(), '+00:00', '+09:00')), WEEKDAY(DATE(CONVERT_TZ(UTC_TIMESTAMP(), '+00:00', '+09:00')))),
	                  SUBDATE(EDU_START_DT, WEEKDAY(EDU_START_DT))) / 7) + 1)
WHERE EDU_WEEK IN ('1', '2', '3', 'OVER') AND EDU_START_DT IS NOT NULL;
