-- 되돌리기: DROP TABLE TB_EEP_TRAVEL_PHRASE_M, TB_EEP_TRAVEL_HIDE_M;

-- 검색해서 번역으로 추가한 문장. 6개 언어를 모두 저장해 어떤 언어 쌍으로도 보인다
CREATE TABLE TB_EEP_TRAVEL_PHRASE_M (
	PHRASE_SQ INT          NOT NULL AUTO_INCREMENT,
	SIT_IDX   INT          NOT NULL,
	SRC_LANG  VARCHAR(5)   NOT NULL,
	TXT_KO    VARCHAR(300) NOT NULL,
	TXT_EN    VARCHAR(300) NOT NULL,
	TXT_VI    VARCHAR(300) NOT NULL,
	TXT_JA    VARCHAR(300) NOT NULL,
	TXT_ZH    VARCHAR(300) NOT NULL,
	TXT_TH    VARCHAR(300) NOT NULL,
	REG_IP    VARCHAR(64)      NULL,
	REG_DT    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (PHRASE_SQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 숨긴 문장. 기본 문장은 'b:' + 한국어 문장, 추가한 문장은 'a:' + PHRASE_SQ
CREATE TABLE TB_EEP_TRAVEL_HIDE_M (
	PHRASE_KEY VARCHAR(320) NOT NULL,
	HIDE_IP    VARCHAR(64)      NULL,
	HIDE_DT    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (PHRASE_KEY)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
