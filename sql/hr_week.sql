-- 교육생 칸반 주차 (2026-11-02). hr_code2.sql 뒤에 한 번만 실행한다
-- EDU_WEEK: 1, 2, 3, OVER(3주차 초과). 비어 있으면 화면에서 시작일이 있으면 1주차, 없으면 시작일 없음으로 본다
-- 되돌리기: ALTER TABLE TB_EEP_HR_TRAINEE_M DROP COLUMN EDU_WEEK;
ALTER TABLE TB_EEP_HR_TRAINEE_M ADD COLUMN EDU_WEEK VARCHAR(10) NULL AFTER EDU_START_DT;

-- 지금 진행중인 교육생만 시작일 기준으로 처음 값을 넣는다. 이후에는 드래그로 옮긴다
UPDATE TB_EEP_HR_TRAINEE_M
SET EDU_WEEK = CASE
	WHEN DATEDIFF(CURDATE(), EDU_START_DT) < 7 THEN '1'
	WHEN DATEDIFF(CURDATE(), EDU_START_DT) < 14 THEN '2'
	WHEN DATEDIFF(CURDATE(), EDU_START_DT) < 21 THEN '3'
	ELSE 'OVER' END
WHERE STATUS_CD = 'ING' AND EDU_START_DT IS NOT NULL;
