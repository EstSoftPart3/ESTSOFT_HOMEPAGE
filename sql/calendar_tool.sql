-- 구글에서 가져온 임시 일정. 관리자별로 마지막 조회 결과만 둔다
CREATE TABLE TB_EEP_CAL_EVT_TMP (
	EVT_TMP_SQ    INT          NOT NULL AUTO_INCREMENT,
	REG_EMPLY_ID  VARCHAR(50)  NOT NULL,
	CAL_ID        VARCHAR(200) NOT NULL,
	GCAL_EVT_ID   VARCHAR(200) NOT NULL,
	EVT_TITLE     VARCHAR(500)     NULL,
	EVT_DESC      TEXT             NULL,
	EVT_LOC       VARCHAR(500)     NULL,
	START_DT      DATETIME     NOT NULL,
	END_DT        DATETIME         NULL,
	ALL_DAY_YN    CHAR(1)      NOT NULL DEFAULT 'N',
	CATE_CD       VARCHAR(20)  NOT NULL,
	SUB_CATE_CD   VARCHAR(20)      NULL,
	REG_DT        DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (EVT_TMP_SQ),
	KEY IX_CAL_EVT_TMP_EMPLY (REG_EMPLY_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 관리자가 확정한 일정. 같은 구글 일정을 다시 확정하면 덮어쓴다
CREATE TABLE TB_EEP_CAL_EVT_M (
	EVT_SQ           INT          NOT NULL AUTO_INCREMENT,
	CAL_ID           VARCHAR(200) NOT NULL,
	GCAL_EVT_ID      VARCHAR(200) NOT NULL,
	EVT_TITLE        VARCHAR(500)     NULL,
	EVT_DESC         TEXT             NULL,
	EVT_LOC          VARCHAR(500)     NULL,
	START_DT         DATETIME     NOT NULL,
	END_DT           DATETIME         NULL,
	ALL_DAY_YN       CHAR(1)      NOT NULL DEFAULT 'N',
	CATE_CD          VARCHAR(20)  NOT NULL,
	SUB_CATE_CD      VARCHAR(20)      NULL,
	CONFIRM_EMPLY_ID VARCHAR(50)  NOT NULL,
	CONFIRM_DT       DATETIME     NOT NULL,
	PRIMARY KEY (EVT_SQ),
	UNIQUE KEY UX_CAL_EVT_M (CAL_ID, GCAL_EVT_ID),
	KEY IX_CAL_EVT_M_START (START_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 1차 분류 키워드 규칙. RULE_ORD 가 작은 것부터 맞춰 보고, '+' 는 모든 단어가 있어야 맞는다(공백 무시)
CREATE TABLE TB_EEP_CAL_RULE_M (
	RULE_SQ     INT          NOT NULL AUTO_INCREMENT,
	KEYWORD     VARCHAR(100) NOT NULL,
	CATE_CD     VARCHAR(20)  NOT NULL,
	SUB_CATE_CD VARCHAR(20)      NULL,
	RULE_ORD    INT          NOT NULL DEFAULT 100,
	USE_YN      CHAR(1)      NOT NULL DEFAULT 'Y',
	PRIMARY KEY (RULE_SQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 구글 OAuth 클라이언트 설정 (GOOGLE_CLIENT_ID, GOOGLE_CLIENT_SECRET). 백오피스 화면에서 입력한다
CREATE TABLE TB_EEP_CAL_CONF_M (
	CONF_KEY VARCHAR(50)  NOT NULL,
	CONF_VAL VARCHAR(500)     NULL,
	UPDT_DT  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (CONF_KEY)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

