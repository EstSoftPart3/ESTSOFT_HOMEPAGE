-- 화면 셀렉트 공통코드(2026-11-12). 화면은 hr_script.jspf 의 HR_ALL_CODES(그룹 HR_·EQP_·LAB_·BONUS_·MEM_)로 읽는다.
-- 코드값(COMN_DTL_CD)은 저장된 데이터·프로그램과 이어져 있어 이름·순서만 바꾼다. 상여 BONUS_*·연구원 역할 LAB_ROLE 은 새 코드를 넣어도 동작이 없다.
-- 다시 돌려도 이미 있는 그룹·코드는 건너뛴다. 되돌리기: 아래 그룹을 공통코드관리에서 삭제
INSERT INTO TB_EEP_COMN_CD_M (COMN_CD, COMN_CD_NM, USE_YN, DEL_YN, REG_DT)
SELECT V.CD, V.NM, 'Y', 'N', DATE_FORMAT(NOW(), '%Y-%m-%d')
FROM (
	          SELECT 'EQP_TYPE' CD, '장비 구분' NM
	UNION ALL SELECT 'EQP_DOC', '장비 첨부 종류'
	UNION ALL SELECT 'LAB_ROLE', '연구원 역할'
	UNION ALL SELECT 'BONUS_TARGET', '상여 받는 사람'
	UNION ALL SELECT 'BONUS_BASE', '상여 기준일'
	UNION ALL SELECT 'BONUS_COND', '상여 단계 조건'
	UNION ALL SELECT 'MEM_GENDER', '계정 성별'
) V
WHERE NOT EXISTS (SELECT 1 FROM TB_EEP_COMN_CD_M C WHERE C.COMN_CD = V.CD AND C.DEL_YN = 'N');

INSERT INTO TB_EEP_COMN_DTL_CD_S (COMN_CD_SQ, COMN_DTL_CD, COMN_DTL_CD_NM, COMN_DTL_CD_ORD, USE_YN, DEL_YN, REG_DT)
SELECT C.COMN_CD_SQ, V.CD, V.NM, V.ORD, 'Y', 'N', DATE_FORMAT(NOW(), '%Y-%m-%d')
FROM (
	          SELECT 'EQP_TYPE' GRP, 'NB' CD, '노트북' NM, 1 ORD
	UNION ALL SELECT 'EQP_TYPE', 'MT', '모니터', 2
	UNION ALL SELECT 'EQP_TYPE', 'DT', '데스크탑', 3
	UNION ALL SELECT 'EQP_TYPE', 'MU', '마우스', 4
	UNION ALL SELECT 'EQP_TYPE', 'KB', '키보드', 5
	UNION ALL SELECT 'EQP_DOC', 'RECEIPT', '영수증', 1
	UNION ALL SELECT 'EQP_DOC', 'ETC', '기타', 2
	UNION ALL SELECT 'LAB_ROLE', 'MEMBER', '연구원', 1
	UNION ALL SELECT 'LAB_ROLE', 'HEAD', '연구소장', 2
	UNION ALL SELECT 'BONUS_TARGET', 'SELF', '본인', 1
	UNION ALL SELECT 'BONUS_TARGET', 'REFERRER', '추천인', 2
	UNION ALL SELECT 'BONUS_BASE', 'JOIN', '입사일', 1
	UNION ALL SELECT 'BONUS_BASE', 'CONTRACT', '계약(투입) 시작일', 2
	UNION ALL SELECT 'BONUS_BASE', 'JOIN_OR_CONTRACT', '입사일 또는 계약 시작일', 3
	UNION ALL SELECT 'BONUS_COND', 'FULL', '만근', 1
	UNION ALL SELECT 'BONUS_COND', 'TENURE', '근속', 2
	UNION ALL SELECT 'BONUS_COND', 'NONE', '조건 없음', 3
	UNION ALL SELECT 'MEM_GENDER', 'M', '남', 1
	UNION ALL SELECT 'MEM_GENDER', 'F', '여', 2
) V
JOIN TB_EEP_COMN_CD_M C ON C.COMN_CD = V.GRP AND C.DEL_YN = 'N'
WHERE NOT EXISTS (SELECT 1 FROM TB_EEP_COMN_DTL_CD_S D WHERE D.COMN_CD_SQ = C.COMN_CD_SQ AND D.COMN_DTL_CD = V.CD AND D.DEL_YN = 'N');
