SET @n := (SELECT IFNULL(MAX(EMPLY_SQ), 0) FROM TB_EEP_EMPLY_M);
UPDATE TB_EEP_EMPLY_M SET EMPLY_SQ = (@n := @n + 1) WHERE EMPLY_SQ IS NULL;

