-- 고객사 직접계약 (2026-11-12): 고객사가 일부를 직접 계약하면 우리 매출 = 매출단가 - 직접계약 금액
-- 되돌리기: ALTER TABLE TB_EEP_DEPLOY_R DROP COLUMN CLIENT_DIRECT_CD, DROP COLUMN CLIENT_DIRECT_AMT; 공통코드 HR_CLIENT_DIRECT 는 공통코드 관리에서 사용 안 함

ALTER TABLE TB_EEP_DEPLOY_R ADD COLUMN IF NOT EXISTS CLIENT_DIRECT_CD varchar(20) NULL COMMENT '고객사 직접계약 종류(공통코드 HR_CLIENT_DIRECT)';
ALTER TABLE TB_EEP_DEPLOY_R ADD COLUMN IF NOT EXISTS CLIENT_DIRECT_AMT bigint NULL COMMENT '고객사 직접계약 금액. 우리 매출 = SALE_PRICE - 이 금액';

INSERT INTO TB_EEP_COMN_CD_M (COMN_CD, COMN_CD_NM, REG_DT, USE_YN, DEL_YN)
SELECT 'HR_CLIENT_DIRECT', '고객사 직접계약', DATE_FORMAT(NOW(), '%Y-%m-%d'), 'Y', 'N' FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM TB_EEP_COMN_CD_M WHERE COMN_CD = 'HR_CLIENT_DIRECT');

INSERT INTO TB_EEP_COMN_DTL_CD_S (COMN_CD_SQ, COMN_DTL_CD, COMN_DTL_CD_NM, COMN_DTL_CD_ORD, REG_DT, USE_YN, DEL_YN)
SELECT C.COMN_CD_SQ, X.CD, X.NM, X.ORD, DATE_FORMAT(NOW(), '%Y-%m-%d'), 'Y', 'N'
FROM TB_EEP_COMN_CD_M C JOIN (SELECT 'REGULAR' CD, '정규직' NM, 1 ORD UNION ALL SELECT 'FREE', '프리', 2) X
WHERE C.COMN_CD = 'HR_CLIENT_DIRECT'
  AND NOT EXISTS (SELECT 1 FROM TB_EEP_COMN_DTL_CD_S D WHERE D.COMN_CD_SQ = C.COMN_CD_SQ AND D.COMN_DTL_CD = X.CD);

SELECT C.COMN_CD, D.COMN_DTL_CD, D.COMN_DTL_CD_NM FROM TB_EEP_COMN_CD_M C JOIN TB_EEP_COMN_DTL_CD_S D ON D.COMN_CD_SQ = C.COMN_CD_SQ WHERE C.COMN_CD = 'HR_CLIENT_DIRECT';
