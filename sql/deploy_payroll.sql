INSERT INTO TB_EEP_COMN_CD_M (COMN_CD, COMN_CD_NM, USE_YN, DEL_YN, REG_DT)
SELECT V.CD, V.NM, 'Y', 'N', DATE_FORMAT(NOW(), '%Y-%m-%d')
