INSERT INTO TB_EEP_COMN_DTL_CD_S (COMN_CD_SQ, COMN_DTL_CD, COMN_DTL_CD_NM, COMN_DTL_CD_ORD, USE_YN, DEL_YN, REG_DT)
SELECT C.COMN_CD_SQ, V.CD, V.NM, V.ORD, 'Y', 'N', DATE_FORMAT(NOW(), '%Y-%m-%d')
FROM (
	          SELECT 'HR_EMP_TYPE' GRP, 'REGULAR' CD, '정규' NM, 1 ORD
	UNION ALL SELECT 'HR_EMP_TYPE', 'PROBATION', '수습', 2
	UNION ALL SELECT 'HR_EMP_TYPE', 'SPECIAL', '특고프리', 3
	UNION ALL SELECT 'HR_EMP_TYPE', 'BIZ', '사업자프리', 4
	UNION ALL SELECT 'HR_EMP_TYPE', 'EMP_INS', '고용보험알바', 5
	UNION ALL SELECT 'HR_EMP_TYPE', 'ETC', '기타계약', 6
	UNION ALL SELECT 'HR_EMP_TYPE', 'EXTERNAL', '외부업체', 7
	UNION ALL SELECT 'HR_DEPLOY_GRADE', '초급', '초급', 1
	UNION ALL SELECT 'HR_DEPLOY_GRADE', '중급', '중급', 2
	UNION ALL SELECT 'HR_DEPLOY_GRADE', '고급', '고급', 3
) V
JOIN TB_EEP_COMN_CD_M C ON C.COMN_CD = V.GRP AND C.DEL_YN = 'N'
WHERE NOT EXISTS (SELECT 1 FROM TB_EEP_COMN_DTL_CD_S D WHERE D.COMN_CD_SQ = C.COMN_CD_SQ AND D.COMN_DTL_CD = V.CD);

