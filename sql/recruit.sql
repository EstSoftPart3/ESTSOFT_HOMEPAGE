-- 모집 관리(/admin/recruit). 앱이 기동할 때 RecruitService.ensureSchema 가 같은 내용을 만들므로 따로 실행하지 않아도 된다(기록용).
-- 메뉴는 투입현황(H00004) 바로 아래에 다음 H 코드로 한 번만 넣고 투입현황 권한 역할에 같이 준다(설정 RECRUIT.MENU_DONE=Y).
-- 모집은 시스템 등록이 주 데이터이고 구글 캘린더와는 연동하지 않는다.

CREATE TABLE IF NOT EXISTS TB_EEP_RECRUIT_M (
	RECRUIT_SQ INT AUTO_INCREMENT PRIMARY KEY, RAW_TEXT TEXT NULL COMMENT '등록 원문',
	CLIENT_NM VARCHAR(200) NULL, PRJ_NM VARCHAR(300) NULL, GRADE_TXT VARCHAR(100) NULL, HEAD_CNT INT NULL,
	START_DT DATE NULL, END_DT DATE NULL, PERIOD_TXT VARCHAR(200) NULL, WORK_AREA VARCHAR(300) NULL, PRICE_TXT VARCHAR(300) NULL, SKILLS VARCHAR(500) NULL, PREFER VARCHAR(500) NULL,
	SALE_PARTNER_SQ INT NULL, SALE_PARTNER_TXT VARCHAR(200) NULL, MGR_NM VARCHAR(100) NULL, CLOSE_DT DATE NULL, MEMO TEXT NULL, STATUS_CD VARCHAR(10) NOT NULL DEFAULT 'OPEN',
	FOLDER_ID VARCHAR(100) NULL, DEL_YN CHAR(1) NOT NULL DEFAULT 'N',
	REG_EMPLY_ID VARCHAR(50) NULL, REG_DT DATETIME NOT NULL, UPDT_EMPLY_ID VARCHAR(50) NULL, UPDT_DT DATETIME NULL
) COMMENT '모집';

CREATE TABLE IF NOT EXISTS TB_EEP_RECRUIT_APPLY_R (
	APPLY_SQ INT AUTO_INCREMENT PRIMARY KEY, RECRUIT_SQ INT NOT NULL, STAFF_SQ INT NOT NULL, STEP_CD VARCHAR(10) NOT NULL DEFAULT 'DOC',
	VER_NO INT NULL, VER_LABEL VARCHAR(50) NULL, FILE_ID VARCHAR(100) NULL, FILE_NM VARCHAR(200) NULL,
	INTV_DT DATETIME NULL, INTV_END_DT DATETIME NULL, INTV_WAY VARCHAR(10) NULL, INTV_PLACE VARCHAR(300) NULL, INTV_WITH VARCHAR(200) NULL,
	DRAFT TEXT NULL COMMENT '투입확정 임시 저장 JSON', DEPLOY_SQ INT NULL, DROP_REASON VARCHAR(500) NULL,
	REG_EMPLY_ID VARCHAR(50) NULL, REG_DT DATETIME NOT NULL, UPDT_EMPLY_ID VARCHAR(50) NULL, UPDT_DT DATETIME NULL,
	UNIQUE KEY UK_RECRUIT_APPLY (RECRUIT_SQ, STAFF_SQ)
) COMMENT '모집 지원';

CREATE TABLE IF NOT EXISTS TB_EEP_RECRUIT_FILE_R (
	FILE_SQ INT AUTO_INCREMENT PRIMARY KEY, RECRUIT_SQ INT NOT NULL, FILE_ID VARCHAR(100) NOT NULL, FILE_NM VARCHAR(300) NOT NULL,
	FILE_SIZE BIGINT NULL, FILE_URL VARCHAR(500) NULL, REG_EMPLY_ID VARCHAR(50) NULL, REG_DT DATETIME NOT NULL, KEY IX_RECRUIT_FILE (RECRUIT_SQ)
) COMMENT '모집 첨부';

CREATE TABLE IF NOT EXISTS TB_EEP_RECRUIT_LOG_H (
	LOG_SQ INT AUTO_INCREMENT PRIMARY KEY, RECRUIT_SQ INT NULL, APPLY_SQ INT NULL, ACT VARCHAR(30) NOT NULL,
	SUMMARY VARCHAR(2000) NULL, EMPLY_ID VARCHAR(50) NULL, REG_DT DATETIME NOT NULL, KEY IX_RECRUIT_LOG (RECRUIT_SQ)
) COMMENT '모집 이력';

