CREATE TABLE IF NOT EXISTS TB_EEP_PAYSLIP_CONF_H (
	  HIST_SQ  bigint NOT NULL AUTO_INCREMENT
	, KIND_CD  varchar(10) NOT NULL COMMENT 'ACCOUNT 계정, BODY 메일 내용, VERIFY 연결 확인'
	, SUMMARY  varchar(500) NOT NULL COMMENT '무엇을 바꿨는지. 비밀번호 값은 남기지 않는다'
	, SUBJECT  varchar(300) NULL COMMENT 'BODY 일 때 그 버전'
	, BODY     mediumtext NULL
	, EMPLY_ID varchar(50) NOT NULL
	, REG_DT   datetime NOT NULL DEFAULT CURRENT_TIMESTAMP
	, PRIMARY KEY (HIST_SQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='급여명세서 메일 설정 이력';

CREATE TABLE IF NOT EXISTS TB_EEP_PAYSLIP_LOG_H (
	  LOG_SQ    bigint NOT NULL AUTO_INCREMENT
	, PAY_YM    char(7) NOT NULL
	, STAFF_SQ  int NOT NULL
	, CHANNEL   varchar(10) NOT NULL COMMENT 'MAIL'
	, TO_ADDR   varchar(200) NULL
	, RESULT    varchar(10) NOT NULL COMMENT 'OK, FAIL'
	, ERROR_MSG varchar(300) NULL
	, EMPLY_ID  varchar(50) NOT NULL
	, REG_DT    datetime NOT NULL DEFAULT CURRENT_TIMESTAMP
	, PRIMARY KEY (LOG_SQ)
	, KEY IX_PAYSLIP_LOG (PAY_YM, STAFF_SQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='급여명세서 발송 이력';

