CREATE TABLE IF NOT EXISTS TB_EEP_PAYROLL_MEMO_R (
	  MEMO_SQ  bigint NOT NULL AUTO_INCREMENT
	, PAY_YM   char(7) NOT NULL
	, STAFF_SQ int NOT NULL
	, CONTENT  varchar(1000) NOT NULL
	, EMPLY_ID varchar(50) NOT NULL
	, REG_DT   datetime NOT NULL DEFAULT CURRENT_TIMESTAMP
	, PRIMARY KEY (MEMO_SQ)
	, KEY IX_PAYROLL_MEMO (STAFF_SQ, PAY_YM)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='급여 메모 (쌓기만, 본인 것만 삭제)';

CREATE TABLE IF NOT EXISTS TB_EEP_PAYROLL_ACK_R (
	  PAY_YM   char(7) NOT NULL
	, STAFF_SQ int NOT NULL
	, FLAG_K   varchar(20) NOT NULL COMMENT '확인 사항 키워드'
	, EMPLY_ID varchar(50) NOT NULL
	, REG_DT   datetime NOT NULL DEFAULT CURRENT_TIMESTAMP
	, PRIMARY KEY (PAY_YM, STAFF_SQ, FLAG_K)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='확인 사항 ✕ 로 확인 완료한 것';
