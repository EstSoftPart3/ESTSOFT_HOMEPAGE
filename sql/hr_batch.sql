-- 되돌리기: DROP TABLE TB_EEP_BATCH_LOG; ALTER TABLE TB_EEP_HR_INTV_M DROP KEY UX_HR_INTV_GCAL, DROP COLUMN GCAL_EVT_ID;
SET NAMES utf8mb4;

-- 어떤 캘린더 일정에서 온 행인지. 일정이 옮겨져도 같은 행을 찾기 위해 둔다
ALTER TABLE TB_EEP_HR_INTV_M
	ADD COLUMN GCAL_EVT_ID VARCHAR(200) NULL,
	ADD UNIQUE KEY UX_HR_INTV_GCAL (GCAL_EVT_ID);

-- 배치 실행 이력. STATUS_CD: OK, WARN(해석 못 한 일정 있음), FAIL. SKIP_DETAIL 의 전화번호는 가려서 저장한다
CREATE TABLE TB_EEP_BATCH_LOG (
	BATCH_LOG_SQ INT         NOT NULL AUTO_INCREMENT,
	BATCH_CD     VARCHAR(30) NOT NULL,
	TRIGGER_CD   VARCHAR(10) NOT NULL,
	STATUS_CD    VARCHAR(10) NOT NULL,
	START_DT     DATETIME    NOT NULL,
	END_DT       DATETIME    NOT NULL,
	FROM_DT      DATE            NULL,
	TO_DT        DATE            NULL,
	READ_CNT     INT         NOT NULL DEFAULT 0,
	INSERT_CNT   INT         NOT NULL DEFAULT 0,
	UPDATE_CNT   INT         NOT NULL DEFAULT 0,
	SAME_CNT     INT         NOT NULL DEFAULT 0,
	EXCL_CNT     INT         NOT NULL DEFAULT 0,
	SKIP_CNT     INT         NOT NULL DEFAULT 0,
	SKIP_DETAIL  TEXT            NULL,
	ERROR_MSG    VARCHAR(500)    NULL,
	PRIMARY KEY (BATCH_LOG_SQ),
	KEY IX_BATCH_LOG_CD (BATCH_CD, START_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
