CREATE TABLE IF NOT EXISTS TB_EEP_BONUS_M (
	  BONUS_SQ      int NOT NULL AUTO_INCREMENT
	, BONUS_NM      varchar(50) NOT NULL
	, BASE_CD       varchar(20) NOT NULL COMMENT 'JOIN 입사일, CONTRACT 계약 시작일, JOIN_OR_CONTRACT 정규·수습은 입사일 그 외 계약 시작일'
	, TARGET_CD     varchar(10) NOT NULL DEFAULT 'SELF' COMMENT 'SELF 본인, REFERRER 추천인(기준일은 추천한 인재 것)'
	, STEPS         varchar(500) NOT NULL COMMENT '개월:조건:금액 를 쉼표로. 조건 FULL 만근, TENURE 근속, NONE 없음'
	, PER_AMT_YN    char(1) NOT NULL DEFAULT 'N' COMMENT '직원관리에서 사람별 금액'
	, USE_YN        char(1) NOT NULL DEFAULT 'Y'
	, SORT_NO       int NOT NULL DEFAULT 0
	, UPDT_EMPLY_ID varchar(50) NULL
	, UPDT_DT       datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
	, PRIMARY KEY (BONUS_SQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='상여 조건. 달성한 달의 익월 급여 상여 칸에 들어간다';

CREATE TABLE IF NOT EXISTS TB_EEP_BONUS_STAFF_R (
	  BONUS_SQ    int NOT NULL
	, STAFF_SQ    int NOT NULL COMMENT '적용 대상(인재추천은 추천받아 들어온 사람)'
	, AMT         bigint NULL COMMENT '사람별 금액, 비면 조건 금액'
	, REFERRER_SQ int NULL COMMENT '인재추천의 추천인'
	, EMPLY_ID    varchar(50) NOT NULL
	, REG_DT      datetime NOT NULL DEFAULT CURRENT_TIMESTAMP
	, PRIMARY KEY (BONUS_SQ, STAFF_SQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='직원관리에서 켠 상여';

