-- 교육생 -> 직원관리 대기 카드 연결 (2026-11-12). 교육진행중·교육종료 교육생은 대기 카드를 갖고, 중도이탈하면 대기 카드를 지운다.
ALTER TABLE TB_EEP_HR_STAFF_M ADD COLUMN IF NOT EXISTS TRN_SQ int NULL COMMENT '교육생에서 자동으로 만든 대기 카드의 교육생 번호';
CREATE UNIQUE INDEX IF NOT EXISTS UX_STAFF_TRN ON TB_EEP_HR_STAFF_M (TRN_SQ);

-- 지금 교육진행중인 교육생의 대기 카드 (교육종료 이력은 이미 채용된 사람이 섞여 있어 넣지 않는다)
INSERT INTO TB_EEP_HR_STAFF_M (STATUS_CD, STAFF_NM, ORG_NM, PHONE, TRN_SQ, UPDT_EMPLY_ID, UPDT_DT)
SELECT 'WAIT', T.TRN_NM, '교육생', I.PHONE, T.TRN_SQ, 'TRAINEE_SYNC', NOW()
FROM TB_EEP_HR_TRAINEE_M T LEFT JOIN TB_EEP_HR_INTV_M I ON I.INTV_SQ = T.INTV_SQ
WHERE T.STATUS_CD = 'ING' AND NOT EXISTS (SELECT 1 FROM TB_EEP_HR_STAFF_M S WHERE S.TRN_SQ = T.TRN_SQ);

-- 이름만 적힌 대여 중 기록을 같은 이름의 교육생 대기 카드에 연결한다 (교육생 이름이 한 명뿐일 때만)
UPDATE TB_EEP_EQP_RENT_H r
JOIN (SELECT STAFF_NM, MIN(STAFF_SQ) AS SQ FROM TB_EEP_HR_STAFF_M WHERE STATUS_CD <> 'LEFT' GROUP BY STAFF_NM HAVING COUNT(*) = 1) s ON s.STAFF_NM = r.HOLDER_NM
JOIN TB_EEP_HR_STAFF_M m ON m.STAFF_SQ = s.SQ AND m.TRN_SQ IS NOT NULL
SET r.STAFF_SQ = s.SQ
WHERE r.OPEN_YN = 'Y' AND r.STAFF_SQ IS NULL;
