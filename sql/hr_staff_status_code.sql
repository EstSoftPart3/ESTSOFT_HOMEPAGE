-- 직원관리 재직 상태 공통코드 (2026-11-12). 코드값(WORK/LEFT/WAIT)은 대기 카드·장비 대여·상여 동작과 묶여 있어 이름·순서만 바꾼다.
INSERT INTO TB_EEP_COMN_CD_M (COMN_CD, COMN_CD_NM, REG_DT, USE_YN, DEL_YN)
SELECT 'HR_STAFF_STATUS', '직원 재직 상태', DATE_FORMAT(NOW(), '%Y-%m-%d'), 'Y', 'N' FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM TB_EEP_COMN_CD_M WHERE COMN_CD = 'HR_STAFF_STATUS');

INSERT INTO TB_EEP_COMN_DTL_CD_S (COMN_CD_SQ, COMN_DTL_CD, COMN_DTL_CD_NM, COMN_DTL_CD_ORD, REG_DT, USE_YN, DEL_YN)
SELECT C.COMN_CD_SQ, X.CD, X.NM, X.ORD, DATE_FORMAT(NOW(), '%Y-%m-%d'), 'Y', 'N'
FROM TB_EEP_COMN_CD_M C JOIN (SELECT 'WORK' CD, '재직' NM, 1 ORD UNION ALL SELECT 'LEFT', '퇴사', 2 UNION ALL SELECT 'WAIT', '대기', 3) X
WHERE C.COMN_CD = 'HR_STAFF_STATUS'
  AND NOT EXISTS (SELECT 1 FROM TB_EEP_COMN_DTL_CD_S D WHERE D.COMN_CD_SQ = C.COMN_CD_SQ AND D.COMN_DTL_CD = X.CD);
