SET NAMES utf8mb4;

-- APP_PW_ENC 는 AES-256-GCM 암호문이다. 키는 db.properties 의 mail.crypto.key 에만 둔다
CREATE TABLE TB_EEP_MAIL_ACCT_M (
	MAIL_ACCT_SQ  INT          NOT NULL AUTO_INCREMENT,
	MAIL_ADDR     VARCHAR(190) NOT NULL,
	ACCT_USE      VARCHAR(100) NOT NULL,
	APP_PW_ENC    VARCHAR(255) NOT NULL,
	RGST_EMPLY_ID VARCHAR(50)  NOT NULL,
	RGST_DT       DATETIME     NOT NULL,
	PRIMARY KEY (MAIL_ACCT_SQ),
	UNIQUE KEY UX_MAIL_ACCT_ADDR (MAIL_ADDR)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
